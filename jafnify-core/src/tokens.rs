//! The fixed Jafnify palette and scales.
//!
//! The values live in `design/tokens.toml` and are generated into this module
//! by the build script, so the core, the Android app and the Linux GUI all
//! read the same colours, spacing, type, radius and elevation. The palette is
//! fixed: there is no dynamic colour.

include!(concat!(env!("OUT_DIR"), "/tokens_generated.rs"));

/// The roles that carry body text, paired with the background they sit on.
/// Every pair must clear [BODY_TEXT_MIN_RATIO] in both themes.
pub const BODY_TEXT_PAIRS: [(&str, &str); 7] = [
    ("fg", "bg"),
    ("fg", "surface"),
    ("muted", "bg"),
    ("muted", "surface"),
    ("primary", "primary_on"),
    ("wait_text", "bg"),
    ("wait_text", "surface"),
];

/// The roles that carry state, paired with the background they sit on. These
/// are icons, dots and hairlines, never body text, so they only have to clear
/// [INDICATOR_MIN_RATIO]. The `wait` role is here on purpose: in the light
/// theme it does not reach 4.5:1, so it must never be used for text.
pub const INDICATOR_PAIRS: [(&str, &str); 8] = [
    ("ok", "bg"),
    ("ok", "surface"),
    ("wait", "bg"),
    ("wait", "surface"),
    ("err", "bg"),
    ("err", "surface"),
    ("accent", "bg"),
    ("accent", "surface"),
];

/// WCAG AA minimum contrast for body text.
pub const BODY_TEXT_MIN_RATIO: f64 = 4.5;

/// WCAG AA minimum contrast for icons and state indicators.
pub const INDICATOR_MIN_RATIO: f64 = 3.0;

/// The Android colour resource name of a role.
pub fn android_name(role: &str) -> String {
    format!("jafnify_{role}")
}

/// One Android dimension resource from the generated scales.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Dimen {
    /// The resource name without the `jafnify_` prefix (`spacing_xs`).
    pub name: String,
    /// The value, in `unit`.
    pub value: u32,
    /// `dp` for layout dimensions, `sp` for text.
    pub unit: &'static str,
}

/// Every Android dimension in write-out order: spacing, type, line height,
/// radius, elevation.
pub fn android_dimens() -> Vec<Dimen> {
    let mut dims = Vec::new();
    for (prefix, unit, scale) in [
        ("spacing", "dp", &SPACING_SCALE[..]),
        ("type", "sp", &TYPE_SCALE[..]),
        ("line_height", "sp", &LINE_HEIGHT_SCALE[..]),
        ("radius", "dp", &RADIUS_SCALE[..]),
        ("elevation", "dp", &ELEVATION_SCALE[..]),
    ] {
        for (name, value) in scale {
            dims.push(Dimen {
                name: format!("{prefix}_{name}"),
                value: *value,
                unit,
            });
        }
    }
    dims
}

/// Renders the scales as an Android dimension resource file.
pub fn android_dimens_xml() -> String {
    let mut xml = String::new();
    xml.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    xml.push_str("<!-- Generated by jafnify-tokens from design/tokens.toml. Do not edit. -->\n");
    xml.push_str("<resources>\n");
    for dimen in android_dimens() {
        xml.push_str(&format!(
            "    <dimen name=\"jafnify_{}\">{}{}</dimen>\n",
            dimen.name, dimen.value, dimen.unit
        ));
    }
    xml.push_str("</resources>\n");
    xml
}

/// Renders a palette as an Android colour resource file.
pub fn android_colours_xml(palette: &Palette) -> String {
    let mut xml = String::new();
    xml.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
    xml.push_str("<!-- Generated by jafnify-tokens from design/tokens.toml. Do not edit. -->\n");
    xml.push_str("<resources>\n");
    for (role, value) in palette.entries() {
        xml.push_str(&format!(
            "    <color name=\"{}\">#{:06X}</color>\n",
            android_name(role),
            value
        ));
    }
    xml.push_str("</resources>\n");
    xml
}

/// Reads the colour names and values of an Android colour resource file.
pub fn parse_colours_xml(xml: &str) -> Vec<(String, u32)> {
    let mut colours = Vec::new();
    let mut rest = xml;
    while let Some(start) = rest.find("<color name=\"") {
        rest = &rest[start + "<color name=\"".len()..];
        let Some(name_end) = rest.find('"') else {
            break;
        };
        let name = rest[..name_end].to_string();
        rest = &rest[name_end + 1..];
        let Some(value_start) = rest.find('>') else {
            break;
        };
        rest = &rest[value_start + 1..];
        let Some(value_end) = rest.find('<') else {
            break;
        };
        let value = rest[..value_end].trim();
        let value = value.strip_prefix('#').unwrap_or(value);
        if let Ok(parsed) = u32::from_str_radix(value, 16) {
            colours.push((name, parsed));
        }
        rest = &rest[value_end..];
    }
    colours
}
